/**
 * The lessons' objects as static files: one SVG per lesson at
 * public/lessons/<lesson id>.svg, written by scripts/export-flat-icons.mjs
 * and committed. The app draws them with a plain <img> (no network
 * beyond the file, precached by the service worker), so the fifteen
 * drawings never reach the browser bundle.
 *
 * Each file is the drawing's own plan (primitives.ts `drawingPlan`, the
 * same one FlatDrawing renders), at full detail (the light kept: every
 * place the app draws a lesson's object is 40px or more), with every
 * colour baked from the `.fi` block of flat-icons.css, the one place the
 * tones live, and its clip ids prefixed with the lesson's id so two files
 * inlined on one page could never share one. No comments, no data
 * attributes: the bytes are the drawing.
 *
 * Server and build only: this reads lesson-drawings.ts.
 */
import { LESSON_ICONS, LESSON_OBJECT_KIND } from "./lesson-drawings";
import { drawingPlan, shapeMarkup } from "./primitives";
import { STAT_FLAT_KINDS, STAT_ICONS } from "./stat-drawings";

/** The detail the files are drawn at: over every size ladder's floor, so every layer is kept. */
const EXPORT_PX = 96;

/** The `--fi-*` tones of the `.fi` rule in flat-icons.css, by name (or of the rule whose selector is exactly `selector`). */
export function readTones(css: string, selector = ".fi"): Map<string, string> {
  const at = css.indexOf(`\n${selector} {`);
  if (at < 0) throw new Error(`flat-icons.css has no ${selector} rule`);
  const body = css.slice(css.indexOf("{", at) + 1, css.indexOf("}", at));
  return new Map([...body.matchAll(/(--fi-[\w-]+):\s*(#[0-9a-f]{6})\s*;/gi)].map((m) => [m[1], m[2].toLowerCase()]));
}

/**
 * components/icons/flat/stat-tones.ts: each stat mark's tones by role, lit
 * (the `.fi` rule) and unlit (the light theme's `.fi[data-lit="false"]`),
 * read from flat-icons.css. FlatIcon puts them inside each layer's fill as
 * the fallback, `var(--fi-<kind>-<role>, <hex>)`, so a mark drawn where the
 * stylesheet never arrived (a page opened offline before the worker kept
 * its CSS) keeps its colours rather than drawing black, as the 3D files
 * did (#516 review). With the stylesheet the variable wins: dark, Increase
 * Contrast and every token swap still come from the CSS.
 */
export function statTonesModule(css: string): string {
  const lit = readTones(css);
  const unlit = readTones(css, '.fi[data-lit="false"]');
  const rows = STAT_FLAT_KINDS.map((kind) => {
    const roles = [...new Set(STAT_ICONS[kind].layers.map((l) => l.tone))];
    const map = (tones: Map<string, string>, state: string) =>
      `{ ${roles
        .map((role) => {
          const value = tones.get(`--fi-${kind}-${role}`);
          if (!value) throw new Error(`no ${state} tone --fi-${kind}-${role}`);
          return `${role.includes("-") ? `"${role}"` : role}: "${value}"`;
        })
        .join(", ")} }`;
    return `  ${kind}: {\n    lit: ${map(lit, "lit")},\n    unlit: ${map(unlit, "unlit")},\n  },`;
  });
  return (
    "/**\n" +
    " * Generated by scripts/export-flat-icons.mjs from components/icons/flat/flat-icons.css.\n" +
    " * Do not edit: re-run the script after changing a tone.\n" +
    " *\n" +
    " * Each stat mark's tones by role, lit (`.fi`) and unlit (the light theme's\n" +
    " * `.fi[data-lit=\"false\"]`): the fallback inside each layer's fill,\n" +
    " * `var(--fi-<kind>-<role>, <hex>)`, so a mark drawn without the stylesheet\n" +
    " * keeps its colours rather than drawing black (FlatIcon).\n" +
    " */\n" +
    "export const STAT_TONES: Record<string, { lit: Record<string, string>; unlit: Record<string, string> }> = {\n" +
    rows.join("\n") +
    "\n};\n"
  );
}

/** One lesson's object as a standalone SVG file, its colours baked from `tones`. */
export function lessonSvg(lessonId: string, tones: ReadonlyMap<string, string>): string {
  const kind = LESSON_OBJECT_KIND[lessonId];
  if (!kind) throw new Error(`no object for lesson ${lessonId}`);
  const plan = drawingPlan(LESSON_ICONS[kind], EXPORT_PX, lessonId);
  const tone = (role: string) => {
    const value = tones.get(`--fi-${kind}-${role}`);
    if (!value) throw new Error(`no tone --fi-${kind}-${role}`);
    return value;
  };
  const defs = plan.clips.length
    ? `<defs>${plan.clips.map((c) => `<clipPath id="${c.id}">${c.shapes.map(shapeMarkup).join("")}</clipPath>`).join("")}</defs>`
    : "";
  const body = plan.layers
    .map((l) => {
      const clip = l.clipId ? ` clip-path="url(#${l.clipId})"` : "";
      return `<g fill="${tone(l.tone)}"${clip}>${l.shapes.map(shapeMarkup).join("")}</g>`;
    })
    .join("");
  const inner = plan.transform ? `<g transform="${plan.transform}">${defs}${body}</g>` : defs + body;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="96" height="96">${inner}</svg>\n`;
}

/** Every file the export writes, by its path from the repository's root. */
export function lessonSvgFiles(css: string): Record<string, string> {
  const tones = readTones(css);
  return Object.fromEntries(
    Object.keys(LESSON_OBJECT_KIND)
      .sort()
      .map((id) => [`public/lessons/${id}.svg`, lessonSvg(id, tones)])
  );
}

/**
 * A file's visible box, as fractions of its square (left, top, right,
 * bottom), and its reach: how far its farthest visible pixel stands from
 * the box's centre, as a fraction of the square. A disc of that radius
 * round the box's centre holds the whole object, so the reach is what
 * sizes an object to stand inside its disc (`.home-hero-art`,
 * `.object-disc`) with the same air round every one of the fifteen.
 */
export type ArtBox = { l: number; t: number; r: number; b: number; reach: number };

/** Where Today's card measures an object: alpha over this, of 255 (the rule the art boxes were always measured by). */
export const SEEN_ALPHA = 40;
/** The raster the boxes are measured on. */
export const MEASURE_PX = 560;

/** The visible box in an RGBA raster `n` pixels square, rounded to four places. */
export function visibleBox(rgba: Uint8Array | Buffer, n: number): ArtBox {
  let x0 = n;
  let y0 = n;
  let x1 = -1;
  let y1 = -1;
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (rgba[(y * n + x) * 4 + 3] <= SEEN_ALPHA) continue;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  /* The reach, from the box's centre to the far edge of each seen pixel. */
  const cx = (x0 + x1 + 1) / 2;
  const cy = (y0 + y1 + 1) / 2;
  let far = 0;
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (rgba[(y * n + x) * 4 + 3] <= SEEN_ALPHA) continue;
      const dx = Math.max(Math.abs(x - cx), Math.abs(x + 1 - cx));
      const dy = Math.max(Math.abs(y - cy), Math.abs(y + 1 - cy));
      far = Math.max(far, dx * dx + dy * dy);
    }
  }
  const r4 = (v: number) => Math.round(v * 10000) / 10000;
  return { l: r4(x0 / n), t: r4(y0 / n), r: r4((x1 + 1) / n), b: r4((y1 + 1) / n), reach: r4(Math.sqrt(far) / n) };
}

/** lib/lesson-art-bounds.ts, from each lesson's measured box. */
export function boundsModule(boxes: Readonly<Record<string, ArtBox>>): string {
  const rows = Object.keys(boxes)
    .sort()
    .map((id) => {
      const b = boxes[id];
      return `  "${id}": { l: ${b.l}, t: ${b.t}, r: ${b.r}, b: ${b.b}, reach: ${b.reach} },`;
    });
  return (
    "/**\n" +
    " * Generated by scripts/export-flat-icons.mjs from public/lessons/*.svg.\n" +
    " * Do not edit: re-run the script after changing a drawing.\n" +
    " *\n" +
    ` * Each lesson object's visible box inside its square, as fractions of\n` +
    ` * the square (left, top, right, bottom; each file rasterised at ${MEASURE_PX}px,\n` +
    ` * alpha over ${SEEN_ALPHA} of 255), and its reach: the farthest visible pixel\n` +
    " * from the box's centre, as a fraction of the square. Today's card, the\n" +
    " * recorder's topic card and the welcome's day one stand the object inside\n" +
    " * its disc by these, not by its square (lib/home.ts `artBox`).\n" +
    " */\n" +
    "export const ART_BOUNDS: Record<string, { l: number; t: number; r: number; b: number; reach: number }> = {\n" +
    rows.join("\n") +
    "\n};\n"
  );
}
