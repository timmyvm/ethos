import { existsSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { LESSONS } from "@/content/lessons";
import { ART_BOUNDS } from "./lesson-art-bounds";

/*
 * The lesson icons (#503): the fifteen lesson objects re-rendered in the
 * stat icons' family (#487) and cut by scripts/cut-lesson-icons.mjs. The
 * file names did not move, so every reader (Lessons, the lesson page,
 * Today's card, the topic card) draws them unchanged; this holds what the
 * cut promises: each lesson keeps its full-size source, ships at its two
 * sizes with alpha under a ceiling, is measured for Today's card, and is
 * precached under a cache that moved with the re-cut.
 */
const root = join(__dirname, "..");
const read = (f: string) => readFileSync(join(root, f), "utf8");

/** A WebP's canvas size from its VP8X header (the cut always writes one: it has alpha). */
function webpSize(file: string) {
  const b = readFileSync(file);
  expect(b.toString("ascii", 0, 4)).toBe("RIFF");
  expect(b.toString("ascii", 8, 12)).toBe("WEBP");
  expect(b.toString("ascii", 12, 16)).toBe("VP8X");
  const hasAlpha = (b[20] & 0x10) !== 0;
  return { w: 1 + b.readUIntLE(24, 3), h: 1 + b.readUIntLE(27, 3), hasAlpha };
}

/** The two cuts: the thumbnails, and the 560 for anything drawn over 180px. */
const CUTS = [
  { dir: "public/lessons", px: 360, maxBytes: 24_000 },
  { dir: "public/lessons/large", px: 560, maxBytes: 40_000 },
];

describe("the lesson icons (#503)", () => {
  for (const lesson of LESSONS) {
    it(`${lesson.id} keeps its source and ships at both sizes with alpha, under the ceiling`, () => {
      expect(existsSync(join(root, "assets/lessons-3d", `${lesson.id}.png`))).toBe(true);
      expect(lesson.art).toBe(`/lessons/${lesson.id}.webp`);
      for (const { dir, px, maxBytes } of CUTS) {
        const file = join(root, dir, `${lesson.id}.webp`);
        expect(existsSync(file), file).toBe(true);
        expect(statSync(file).size).toBeLessThanOrEqual(maxBytes);
        expect(webpSize(file)).toEqual({ w: px, h: px, hasAlpha: true });
      }
    });
  }

  it("names every lesson in the cut, and nothing else", () => {
    const cut = read("scripts/cut-lesson-icons.mjs");
    const block = cut.slice(cut.indexOf("const OPTICAL = {"), cut.indexOf("};", cut.indexOf("const OPTICAL = {")));
    const names = [...block.matchAll(/^\s*"([a-z-]+)":/gm)].map((m) => m[1]);
    expect(names.sort()).toEqual(LESSONS.map((l) => l.id).sort());
  });

  it("is measured for Today's card: every box inside its square, with air at the edges", () => {
    expect(Object.keys(ART_BOUNDS).sort()).toEqual(LESSONS.map((l) => l.id).sort());
    expect(read("lib/lesson-art-bounds.ts")).toContain("Generated by scripts/cut-lesson-icons.mjs");
    for (const [id, b] of Object.entries(ART_BOUNDS)) {
      for (const v of [b.l, b.t]) expect(v, id).toBeGreaterThan(0.05);
      for (const v of [b.r, b.b]) expect(v, id).toBeLessThan(0.95);
    }
  });

  it("is precached, under a cache that moved with the re-cut", () => {
    const sw = read("public/sw.js");
    for (const lesson of LESSONS) {
      expect(sw).toContain(`"/lessons/${lesson.id}.webp"`);
      expect(sw).toContain(`"/lessons/large/${lesson.id}.webp"`);
    }
    const v = Number(sw.match(/const CACHE = "ethos-v(\d+)";/)![1]);
    expect(v).toBeGreaterThanOrEqual(20);
  });
});
