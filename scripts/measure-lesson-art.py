"""
Where each lesson object actually is inside its square (Today, #393).

The fifteen glass objects (scripts/cut-lesson-art.mjs, keyed by
scripts/key-lesson-art.py) are cut on one square crop, so an hourglass
fills its square top to bottom while the pause marks, the bowl and the
boomerang sit as a wide low band in the middle. Placed by its square,
only the hourglass rose out of Today's card, and the wide ones ran onto
the card's words. So the card and the tiles place each object by the box
its visible pixels fill, and this script measures that box.

A pixel counts when its alpha is over 40 of 255 (about 16%): the glass
edge and the body of the contact shadow, not the shadow's last haze.
The box is written as fractions of the square, so it holds at any cut
size, into lib/lesson-art-bounds.ts. Run after keying, from the repo:

    python3 scripts/measure-lesson-art.py

It reads the 560 cut (public/lessons/large/), which is what Today draws.
"""

import glob
import os

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "public", "lessons", "large")
OUT = os.path.join(ROOT, "lib", "lesson-art-bounds.ts")
THRESHOLD = 40


def box(path: str) -> tuple[float, float, float, float]:
    alpha = np.array(Image.open(path).convert("RGBA").getchannel("A"))
    h, w = alpha.shape
    seen = alpha > THRESHOLD
    ys = np.where(seen.any(axis=1))[0]
    xs = np.where(seen.any(axis=0))[0]
    return (
        round(xs[0] / w, 4),
        round(ys[0] / h, 4),
        round((xs[-1] + 1) / w, 4),
        round((ys[-1] + 1) / h, 4),
    )


rows = []
for path in sorted(glob.glob(os.path.join(SRC, "*.webp"))):
    name = os.path.splitext(os.path.basename(path))[0]
    l, t, r, b = box(path)
    rows.append(f'  "{name}": {{ l: {l}, t: {t}, r: {r}, b: {b} }},')

with open(OUT, "w") as f:
    f.write(
        "/**\n"
        " * Generated by scripts/measure-lesson-art.py from public/lessons/large/.\n"
        " * Do not edit: re-run the script after re-cutting the art.\n"
        " *\n"
        " * Each lesson object's visible box inside its square, as fractions of\n"
        " * the square (left, top, right, bottom; alpha over 40 of 255). Today's\n"
        " * card and tiles size and place an object by this box, not by its\n"
        " * square (lib/home.ts `artBox`).\n"
        " */\n"
        "export const ART_BOUNDS: Record<string, { l: number; t: number; r: number; b: number }> = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )
print(f"wrote {len(rows)} boxes to {os.path.relpath(OUT, ROOT)}")
